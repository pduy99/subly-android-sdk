#!/usr/bin/env python3
"""Generate src/main/cpp/opencl_shim.cpp: OpenCL entry points that forward
to the device's vendor libOpenCL.so, resolved with dlopen at first use.

Why not link libOpenCL.so: Android has no NDK OpenCL library, and a
DT_NEEDED on it makes libwhisper_jni.so fail to load on any phone whose
vendor does not expose OpenCL to apps, taking CPU transcription down with
it. Forwarding through dlopen keeps the library loadable everywhere; where
OpenCL is missing every call reports "no platform" and ggml registers no
OpenCL device, so whisper.cpp runs on the CPU.

Run from the module directory after changing FUNCTIONS (the OpenCL entry
points ggml-opencl.cpp calls):
    python3 tools/gen_opencl_shim.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CPP = os.path.join(HERE, "..", "src", "main", "cpp")
HEADER = os.path.join(CPP, "third_party", "OpenCL-Headers", "CL", "cl.h")
OUT = os.path.join(CPP, "opencl_shim.cpp")
GGML_OPENCL = os.path.join(CPP, "ggml", "src", "ggml-opencl", "ggml-opencl.cpp")

PROTO = re.compile(
    r"extern\s+CL_API_ENTRY\s+(?P<ret>[\w\s\*]+?)\s+CL_API_CALL\s+(?P<name>cl\w+)\s*"
    r"\((?P<params>.*?)\)\s*CL_API_SUFFIX",
    re.S,
)


def functions_used():
    with open(GGML_OPENCL) as f:
        src = f.read()
    return sorted(set(re.findall(r"\b(cl[A-Z]\w*)\s*\(", src)))


def split_params(params):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [" ".join(p.split()) for p in out]


def param_name(param):
    fp = re.search(r"\(\s*CL_CALLBACK\s*\*\s*(\w+)\s*\)", param)
    if fp:
        return fp.group(1)
    m = re.search(r"(\w+)\s*(\[\s*\w*\s*\])?$", param)
    return m.group(1)


def main():
    with open(HEADER) as f:
        header = f.read()
    protos = {m.group("name"): m for m in PROTO.finditer(header)}
    wanted = functions_used()
    missing = [n for n in wanted if n not in protos]
    if missing:
        sys.exit(f"not declared in cl.h: {missing}")

    lines = [
        "// GENERATED by tools/gen_opencl_shim.py. Do not edit; rerun the script.",
        "//",
        "// OpenCL entry points forwarded to the vendor libOpenCL.so, resolved",
        "// with dlopen on first use. See the script for why this is not a link",
        "// dependency.",
        "",
        "#define CL_TARGET_OPENCL_VERSION 300",
        "#include <CL/cl.h>",
        "#include <CL/cl_ext.h>",
        "#include <dlfcn.h>",
        "#include <mutex>",
        "",
        "namespace {",
        "",
        "void * vendor_library() {",
        "    static void * handle = nullptr;",
        "    static std::once_flag once;",
        "    std::call_once(once, [] {",
        "        // Apps reach the vendor library through the public-libraries",
        "        // namespace; the manifest declares it with <uses-native-library>.",
        "        const char * candidates[] = {",
        '            "libOpenCL.so",',
        '            "/vendor/lib64/libOpenCL.so",',
        '            "/system/vendor/lib64/libOpenCL.so",',
        "        };",
        "        for (const char * path : candidates) {",
        "            handle = dlopen(path, RTLD_NOW | RTLD_LOCAL);",
        "            if (handle != nullptr) break;",
        "        }",
        "    });",
        "    return handle;",
        "}",
        "",
        "template <typename F>",
        "F resolve(const char * name) {",
        "    void * lib = vendor_library();",
        "    return lib == nullptr ? nullptr : reinterpret_cast<F>(dlsym(lib, name));",
        "}",
        "",
        "}  // namespace",
        "",
        'extern "C" int subly_opencl_available() { return vendor_library() != nullptr; }',
        "",
    ]

    for name in wanted:
        m = protos[name]
        ret = " ".join(m.group("ret").split())
        params = split_params(m.group("params"))
        if params == ["void"]:
            params = []
        names = [param_name(p) for p in params]
        sig = ", ".join(params) if params else "void"

        if ret == "cl_int":
            if name == "clGetPlatformIDs":
                fallback = "if (num_platforms != nullptr) *num_platforms = 0; return CL_PLATFORM_NOT_FOUND_KHR;"
            else:
                fallback = "return CL_INVALID_PLATFORM;"
        elif "errcode_ret" in names:
            fallback = "if (errcode_ret != nullptr) *errcode_ret = CL_INVALID_PLATFORM; return nullptr;"
        elif ret.endswith("*") or ret.startswith("cl_") and ret not in ("cl_int", "cl_uint"):
            fallback = "return nullptr;"
        else:
            sys.exit(f"no fallback rule for {name} returning {ret}")

        lines += [
            f'extern "C" CL_API_ENTRY {ret} CL_API_CALL {name}({sig}) {{',
            f"    static auto fn = resolve<decltype(&{name})>(\"{name}\");",
            f"    if (fn == nullptr) {{ {fallback} }}",
            f"    return fn({', '.join(names)});",
            "}",
            "",
        ]

    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)}: {len(wanted)} functions")


if __name__ == "__main__":
    main()
